// Writes frontend/config.js from environment variables.
//
// Cloudflare Pages build command: node frontend/build-config.mjs
//   STATUS_API        (required on Pages) API base URL, e.g. https://status-api.example.com
//   STATUS_TITLE      (optional) title at the top of the page, default "Status"
//   STATUS_TAB_TITLE  (optional) browser tab title, default STATUS_TITLE
//
// Locally, STATUS_API defaults to http://localhost:4040.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const env = process.env;
const onPages = Boolean(env.CF_PAGES);

const api = (env.STATUS_API || (onPages ? "" : "http://localhost:4040")).trim().replace(/\/+$/, "");
if (!api) fail("STATUS_API is not set. Add it under Pages > Settings > Variables and Secrets.");
let url;
try {
  url = new URL(api);
} catch {
  fail(`STATUS_API is not a valid URL: ${api}`);
}
if (url.protocol !== "https:" && url.protocol !== "http:") fail(`STATUS_API must be http(s): ${api}`);

const title = (env.STATUS_TITLE || "").trim() || "Status";
const tabTitle = (env.STATUS_TAB_TITLE || "").trim() || title;

// JSON.stringify makes every value a safe JS string literal.
const out =
  "// Generated by build-config.mjs. Do not edit or commit.\n" +
  `window.STATUS_API = ${JSON.stringify(api)};\n` +
  `window.STATUS_TITLE = ${JSON.stringify(title)};\n` +
  `window.STATUS_TAB_TITLE = ${JSON.stringify(tabTitle)};\n`;

const dest = fileURLToPath(new URL("./config.js", import.meta.url));
writeFileSync(dest, out);
console.log(`wrote ${dest}\n${out}`);

function fail(msg) {
  console.error(`build-config: ${msg}`);
  process.exit(1);
}
